/**
 * 出版社の並び替えに使う文字列。
 * 読みが分かればカナ、分からなければ名前そのもの。
 */
export function publisherSortKey(publisher: string): string {
  const name = publisher.trim();
  return PUBLISHER_KANA[name] ?? name;
}

/**
 * 読みを持っている出版社か。
 * 表の取りこぼしを調べるために公開している。
 */
export function hasPublisherKana(publisher: string): boolean {
  return publisher.trim() in PUBLISHER_KANA;
}
